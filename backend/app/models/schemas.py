"""
Pydantic schemas — API request/response contracts.

DECISION: Separate schemas from ORM models
  ORM models define how data is STORED (database columns, relationships).
  Pydantic schemas define how data is TRANSMITTED (API shape, validation).
  
  These often differ:
  - DB stores embedding vectors; API never exposes them.
  - DB stores internal IDs; API may use slugs.
  - Request schemas validate input; DB models don't know about HTTP.
  
  Coupling them (e.g., returning ORM objects directly) leaks internals
  and makes it impossible to change the DB schema without breaking the API.

DECISION: Separate Create/Response schemas over a single model
  ChatMessageCreate has the fields a client SENDS (content only).
  ChatMessageResponse has the fields a client RECEIVES (content + sources + model).
  One schema for both would either expose internal fields in requests or
  hide useful fields in responses.
"""

from datetime import datetime
from uuid import UUID

from pydantic import BaseModel, Field


# =============================================================================
# Session Schemas
# =============================================================================

class SessionCreate(BaseModel):
    """Request body for creating a new chat session."""
    title: str | None = Field(
        None,
        max_length=255,
        description="Optional title. Auto-generated from first message if omitted.",
    )
    metadata: dict = Field(
        default_factory=dict,
        description="Optional key-value metadata (e.g., user preferences).",
    )


class SessionResponse(BaseModel):
    """A chat session as returned by the API."""
    id: UUID
    title: str | None
    created_at: datetime
    updated_at: datetime
    metadata: dict
    message_count: int = Field(
        0, description="Number of messages in this session."
    )

    model_config = {"from_attributes": True}
    # from_attributes=True lets us construct this from an ORM Session object:
    #   SessionResponse.model_validate(session_orm_obj)


class SessionListResponse(BaseModel):
    """Paginated list of sessions."""
    sessions: list[SessionResponse]
    total: int


# =============================================================================
# Message Schemas
# =============================================================================

class ChatMessageCreate(BaseModel):
    """Request body for sending a chat message."""
    content: str = Field(
        ...,  # Required
        min_length=1,
        max_length=10000,
        description="The user's message text.",
    )
    # DECISION: No role field in the request
    #   The client always sends user messages. The backend creates assistant
    #   messages. Letting the client set role="assistant" would be a bug vector.


class SourceReference(BaseModel):
    """A reference to a transcript chunk that grounded an answer."""
    transcript: str = Field(description="Transcript filename or episode title.")
    chunk_id: str = Field(description="Chunk identifier for traceability.")
    text: str = Field(description="The relevant excerpt from the transcript.")
    relevance_score: float = Field(
        description="Cosine similarity score (0-1). Higher = more relevant."
    )


class ArtifactData(BaseModel):
    """An artifact (Markdown or HTML) generated by the assistant."""
    type: str = Field(description="'markdown' or 'html'")
    content: str = Field(description="The rendered content.")
    title: str | None = Field(None, description="Optional artifact title.")


class ChatMessageResponse(BaseModel):
    """A chat message as returned by the API."""
    id: UUID
    session_id: UUID
    role: str
    content: str
    sources: list[SourceReference] = []
    artifact: ArtifactData | None = None
    model_used: str | None = None
    created_at: datetime

    model_config = {"from_attributes": True}


class ChatResponse(BaseModel):
    """
    Full response to a chat request.
    
    DECISION: Wrap the message in a response object
      This allows adding metadata (latency, token count) without changing
      the message schema. Extensible without breaking existing clients.
    """
    message: ChatMessageResponse
    session_id: UUID
    model: str = Field(description="Which LLM model generated this response.")


# =============================================================================
# Health & Config Schemas
# =============================================================================

class HealthStatus(BaseModel):
    """Health check response."""
    status: str = Field(description="'healthy' or 'degraded'")
    database: str = Field(description="'connected' or 'error: ...'")
    ollama: str = Field(description="'connected' or 'unavailable' or 'not configured'")
    knowledge_base: str = Field(description="'loaded (N chunks)' or 'empty'")
    version: str = "0.1.0"


class ModelConfigResponse(BaseModel):
    """Current LLM configuration."""
    active_provider: str
    active_model: str
    available_providers: list[str] = ["ollama", "anthropic", "openai"]


# =============================================================================
# Error Schemas
# =============================================================================

class ErrorResponse(BaseModel):
    """
    Standardized error response.
    
    DECISION: Structured errors over plain strings
      {"error": "session_not_found", "detail": "No session with ID abc-123"}
      is programmatically parseable. The frontend can show different UI for
      different error types. A plain "Not found" string gives the client nothing
      to work with.
    """
    error: str = Field(description="Machine-readable error code (e.g., 'session_not_found').")
    detail: str = Field(description="Human-readable explanation.")
    status_code: int
